from linkedin_games import Tango


def test_tango_151():
    tango = Tango(
        filled_squares={(1,2): 1, (1,5): 1, (5,2): 0, (5,5): 1},
        matching_pairs=[
            ((2,3), (2,4)), ((2,1), (3,1)), ((2,3), (3,3)),
            ((2,6), (3,6)), ((4,1), (4,2)), ((6,3), (6,4))
        ],
        opposite_pairs=[((2,4), (3,4)), ((3,1), (4,1)), ((3,3), (3,4)), ((3,6), (4,6)), ((4,5), (4,6))]
    )
    tango.solve()
    solution = {
        (1,1): 1, (1,2): 1, (1,3): 0, (1,4): 0, (1,5): 1, (1,6): 0,
        (2,1): 0, (2,2): 0, (2,3): 1, (2,4): 1, (2,5): 0, (2,6): 1,
        (3,1): 0, (3,2): 1, (3,3): 1, (3,4): 0, (3,5): 0, (3,6): 1,
        (4,1): 1, (4,2): 1, (4,3): 0, (4,4): 0, (4,5): 1, (4,6): 0,
        (5,1): 1, (5,2): 0, (5,3): 0, (5,4): 1, (5,5): 1, (5,6): 0,
        (6,1): 0, (6,2): 0, (6,3): 1, (6,4): 1, (6,5): 0, (6,6): 1
    }
    assert tango.solution == solution


