from linkedin_games import Zip


def test_zip_166():
    numbered_squares = [
        (6,5), (6,6), (5,6), (6,4), (5,3), (4,2), (3,1), (2,1),
        (1,1), (1,2), (1,3), (3,5), (2,4), (3,4), (4,3), (4,6)
    ]
    zip_game = Zip(6, numbered_squares)
    zip_game.solve()
    path = [
        (6,5), (6,6), (5,6), (5,5), (5,4), (6,4),
        (6,3), (5,3), (5,2), (6,2), (6,1), (5,1),
        (4,1), (4,2), (3,2), (3,1), (2,1), (1,1),
        (1,2), (2,2), (2,3), (1,3), (1,4), (1,5),
        (1,6), (2,6), (3,6), (3,5), (2,5), (2,4),
        (3,4), (3,3), (4,3), (4,4), (4,5), (4,6)
    ]
    assert zip_game.path == path


